export type SourceLink = { label: string; url: string };

export type RiskLevel = "low" | "medium" | "high";

export type CardTone =
  | "emerald"
  | "sky"
  | "blue"
  | "amber"
  | "violet"
  | "purple"
  | "rose"
  | "teal";

export type ReportBlock =
  | {
      kind: "facts";
      /** Горен, „водещ“ ред с по-едри кутийки (до 3 броя). */
      featured?: boolean;
      /** Малко заглавие над кутийките (напр. „От Стара Загора“). */
      title?: string;
      items: {
        label: string;
        value: string;
        /** "md" е двойно по-широка от стандартната ("sm", по подразбиране) кутийка — за стойност с повече обяснителен текст. */
        size?: "sm" | "md";
        description?: string;
        pillLabel?: string;
        pillValue?: string;
        sources?: SourceLink[];
      }[];
    }
  | {
      kind: "text";
      title?: string;
      body: string;
      /** "dark" — тъмна карта (медиен преглед); "highlight" — фолклорен акцент. */
      variant?: "default" | "dark" | "highlight" | "alert";
      /** Цвят на подкатегорията (оцветена карта със заглавие по средата). */
      tone?: CardTone;
    }
  | { kind: "list"; title?: string; items: string[]; tone?: CardTone }
  | {
      /** Двускален индикатор (напр. качество на водата + стабилност на снабдяването). */
      kind: "scale";
      title?: string;
      items: {
        label: string;
        level: "good" | "fair" | "poor";
        /** Дума/до 3 думи, показвана голяма (напр. "Добро", "Нестабилно"). */
        levelText: string;
        percent: number;
        note: string;
        sources?: SourceLink[];
      }[];
    }
  | {
      kind: "distances";
      title?: string;
      rows: {
        to: string;
        distance: string;
        driveTime: string;
        /** Само дали има влакова връзка/гара — без време и разписание. */
        hasTrain?: boolean;
        road?: string;
        /** Защо мястото е известно/релевантно — показва се като „i“ бутон при посочване. */
        info?: string;
      }[];
    }
  | {
      kind: "gauge";
      title: string;
      /** Процент 0–100 (абсолютна стойност на промяната). */
      value: number;
      direction: "up" | "down" | "neutral";
      periodLabel?: string;
      note?: string;
    }
  | {
      kind: "cards";
      title?: string;
      items: { icon?: string; label: string; body: string; tone: CardTone }[];
    }

  | {
      kind: "pie";
      title: string;
      note?: string;
      data: { name: string; value: number }[];
    }
  | {
      kind: "schedule";
      title: string;
      note?: string;
      rows: { route: string; days: string; runs: string; last: string }[];
    }
  | {
      kind: "risks";
      title: string;
      items: {
        label: string;
        level: RiskLevel;
        note?: string;
        /** 0–100; ако липсва, се извежда от level (low=20, medium=50, high=80). */
        percent?: number;
        incidentCount?: number;
        sources?: SourceLink[];
      }[];
    }
  | { kind: "checklist"; title?: string; items: { title: string; points: string[] }[] };

